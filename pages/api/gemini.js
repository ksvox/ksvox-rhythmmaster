// pages/api/gemini.js
// リズムAIマスター - Gemini API呼び出し用サーバーサイドAPIルート
// Dify版プロンプトのABC記法ルールをそのまま移植し、BPM/LEVELを渡してリズム譜を生成する

function buildPrompt(bpm, level) {
  return `# 役割とミッション
あなたはリズム感を鍛え上げる「リズムAIマスター」アプリです。
ユーザーから入力される変数（BPM=${bpm} と LEVEL=${level}）を厳密に読み解き、各レベルに応じた「正確な4小節のリズム譜（ABC記法）」を即興で作曲して出力してください。

# ユーザー入力変数
* BPM（テンポ）：${bpm}
* LEVEL（難易度）：${level}

# 楽譜生成の絶対ルール（ABC記法）
出力するABC記法は、以下のフォーマットと制限を1ミリの狂いもなく厳守すること。

1. **ヘッダー設定**:
   - \`X:1\`
   - \`L:1/8\`（音符の基準の長さを「8分音符」に設定。C2が4分音符、Cが8分音符となる）
   - \`K:C\`（この行は後でプログラム側に上書きされるため、内容は気にせず必ず1行存在させること）

2. **音符の長さ（基本単位L:1/8）**:
   - 16分音符: C/2
   - 8分音符: C
   - 4分音符: C2
   - 2分音符: C4
   - 休符: z（8分）, z2（4分）, z4（2分）, z/2（16分）
   - 付点音符は使用しない。
   - 【重要】長さを表す数字や記号は、必ず音符の文字(C)より"後ろ"に書くこと（正: C2 ／ 誤: 2C）。

3. **1拍（2ユニット）ごとの部品化ルール（最重要・必ずこの通りに組み立てる）**:
   L:1/8のとき、1拍＝ちょうど「2ユニット」である。1小節＝4拍＝8ユニット。
   各小節は、必ず下記A・B・Cの「パーツ」だけを組み合わせて作ること。パーツにない音符の並べ方を勝手に作ってはならない。

   【A. 1拍で完結するパーツ（単独で2ユニット、タイは使わない）】
   - 4分音符: \`C2\`
   - 8分＋8分（連桁）: \`CC\`
   - 16分＋16分＋8分（連桁）: \`C/2C/2C\`
   - 8分＋16分＋16分（連桁）: \`CC/2C/2\`
   - 16分＋8分＋16分（連桁）: \`C/2CC/2\`
   - 16分×4（連桁）: \`C/2C/2C/2C/2\`
   - 4分休符: \`z2\`
   - 8分休符＋8分音符: \`zC\`
   - 8分音符＋8分休符: \`Cz\`
   - 16分休符＋16分＋8分: \`z/2C/2C\`
   - 8分＋16分＋16分休符: \`CC/2z/2\`

   【B. 拍をまたぐシンコペーション専用パーツ（必ずこの形のまま使い、分解しないこと）】
   - 2拍目ウラ→3拍目の頭にタイでつなぐ（2拍目＋3拍目のセット。4ユニット）: \`zC-C2\`
   - 【絶対禁止】小節をまたぐタイ（今の小節の最後の音を、次の小節の頭までタイでつなぐ書き方）は、絶対に使用しないこと。シンコペーションは、必ず1つの小節の中で完結させること（上記の \`zC-C2\` のパターンのみ使用可）。
   - 【絶対禁止】"|" は、各小節の一番最後（8ユニット消費した直後）にしか書いてはならない。小節の途中に "|" を書くことは絶対禁止。

   【C. 2拍（4ユニット）で完結するパーツ（必ず1拍目または3拍目の頭からのみ使用可）】
   - 2分音符: \`C4\`

   【D. 絶対禁止】
   - 同じ1拍の中で音符同士をタイ「-」でつなぐことは禁止（例：「C-C」は間違い。これはただの4分音符なので必ず \`C2\` と書く）。
   - タイは、上記Bのパーツを使う場合にのみ使用可。それ以外の場面でタイ記号「-」を書いてはならない。
   - パーツとパーツの間には、必ず半角スペースを1つ入れて区切ること。
   - 【絶対禁止】\`C/2C/2\`(16分音符2つだけ)を、それ単独で1拍として使うことは絶対禁止。これは1ユニットしかなく、2ユニット＝1拍に足りない。16分音符を使いたい場合は、必ずAのリストにある \`C/2C/2C\`／\`CC/2C/2\`／\`C/2C/2C/2C/2\`／\`z/2C/2C\`／\`CC/2z/2\` のいずれか(すべて合計2ユニットになる形)のみを使うこと。

4. **難易度別生成ロジック（レベル1-10。数字が大きいほど難易度が高い）**:
   各レベルの「4小節中、何小節に16分音符パーツ(A内の16分を含む形)を使うか」「4小節中、何小節にBパーツ(シンコペーション)を使うか」の最低数を厳守し、**レベルが上がるほど必ず難易度指標(16分音符を含む小節数＋シンコペーション小節数の合計)が高くなる**ようにすること。数字を守れば自然と難易度が積み上がる設計になっている。

   - レベル1: 4分音符(C2)と8分音符(CC)のみ。16分音符なし・休符なし・シンコペーションなし。
   - レベル2: レベル1の音符に、4分休符(z2)と8分休符(zC／Cz)を追加。16分音符なし・シンコペーションなし。
   - レベル3: レベル2に2分音符(C4)を追加。16分音符なし・シンコペーションなし。
   - レベル4: 【16分音符を含む小節：4小節中1小節以上】。シンコペーションはまだ使わない。
   - レベル5: 【16分音符を含む小節：4小節中1小節以上】＋【シンコペーション(Bパーツ)：4小節中ちょうど1小節】。
   - レベル6: 【16分音符を含む小節：4小節中2小節以上】＋【シンコペーション：4小節中1小節】＋裏打ち(8分ウラから始まる形)を1箇所以上含める。
   - レベル7: 【16分音符を含む小節：4小節中3小節以上】＋【シンコペーション：4小節中1小節】。
   - レベル8: 【16分音符を含む小節：4小節中2小節以上】＋【シンコペーション：4小節中1小節】＋2分音符(C4)を1箇所以上含め、A・B・Cのパーツ全種類を必ずどこかに使う（バラエティ重視のレベル）。
   - レベル9: 【16分音符を含む小節：4小節中3小節以上】＋【シンコペーション：4小節中2小節】。
   - レベル10: 【16分音符を含む小節：4小節すべて】＋【シンコペーション：4小節中2小節以上】。体感的に最も難しいリズムにする。
   - 【全レベル共通・絶対禁止】上記A・B・Cのパーツにない、新しい音符の並べ方や書き方を独自に考案するのは禁止。
   - 【出力前の自己チェック】完成後、実際に「16分音符を含む小節の数」と「シンコペーションを含む小節の数」を数え、そのレベルの最低基準を満たしているか必ず確認すること。基準に満たない場合は、満たすまで組み立て直すこと。

5. **構成ルール**:
   - 【最重要・Bパーツ使用時の絶対ルール】Bパーツ(\`zC-C2\`)は単独で2拍分(4ユニット)です。Bパーツを1小節の中で1回使った場合、その小節の残りは、必ず「Aパーツをちょうど2個」だけ追加すること。3個以上追加すると拍が余り、1個以下だと拍が足りなくなる。
   - 【最重要・Cパーツ使用時の絶対ルール】Cパーツ(\`C4\`)は、単独で2拍分(4ユニット)です。Cパーツを1小節の中で1回使った場合、その小節の残りは、必ず「Aパーツをちょうど2個」だけ追加すること（またはCパーツ2個で小節を完結させること）。
   - 【間違いの具体例・絶対にこの形にしないこと】\`C/2C/2C/2C/2 zC-C2 C/2C/2C z/2C/2C\` のように、Bパーツのあとに3つ以上のAパーツを並べるのは間違い。合計が1+2+1+1=5拍になってしまう。
   - 【正しい具体例】Bパーツを使う場合は \`(Aパーツ1個) zC-C2 (Aパーツ1個)\` のように、前後に1個ずつ、合計2個のAパーツだけを添えること。
   - 1小節は、上記「A・B・Cのパーツ」を合計4拍分になるよう組み合わせて作ること（例：Aのみなら4個、Bを使うならAパーツ2個＋B1個、Cを使うならAパーツ2個＋C1個、など）。それ以外の方法で音符を並べてはならない。Cのパーツ（2分音符）は、必ず1拍目または3拍目の頭からのみ使用すること。
   - パーツを正しく組み合わせれば自動的に1小節＝8ユニットになる。念のため、完成した小節が本当に8ユニットになっているか最後に確認すること。
   - 各小節は必ず半角の \`|\` で区切ること。
   - 各小節の直後で必ず改行すること（1小節＝1行として出力し、必ず4行になるようにする）。1行に複数の小節を書いてはならない。
   - 最後の小節の末尾には終止線 \`|]\` を置くこと。
   - 出力前に、各小節に含まれる "|" の数を数え、想定通りの位置（各小節の末尾のみ）にしかないかを必ず確認すること。小節の途中に "|" が紛れ込んでいたら、その小節は絶対に出力してはならない。
   - 単調な繰り返しを避け、パーツの組み合わせにバリエーションを持たせること。

   **出力形式の見本（レベル5・4/4拍子。パーツの組み合わせ方の参考。実際の中身はレベルに応じて毎回変えること）**:
K:C
L:1/8
C2 CC C4|
C/2C/2C/2C/2 zC-C2 C2|
z2 CC C2 Cz|
CC/2C/2 C2 z2 CC|]

# 厳格な制約事項（絶対死守）
1. 出力は、指定されたJSONスキーマの"abc"フィールドの中に、ABC記法のテキストのみを文字列として格納すること。挨拶や説明、Markdownのコードブロック記号（\`\`\`abc など）はabcフィールドの中に含めないこと。
2. 同じBPM・同じLEVELで生成を依頼された場合でも、前回と全く同じパターンを繰り返さず、毎回できるだけ異なるバリエーションのリズムを新しく作り出すこと。ただしパーツのルール(A・B・C)や難易度別ロジックは厳守すること。
3. ユーザーから指定された1つの難易度（レベル）のみを生成すること。全レベルのパターンを連続して出力するなどの暴走は絶対に禁止すること。`;
}

async function callGemini({ apiKey, model, prompt }) {
  const response = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [
          {
            role: 'user',
            parts: [{ text: prompt }],
          },
        ],
        generationConfig: {
          temperature: 0.8,
          thinkingConfig: { thinkingLevel: 'MEDIUM' },
          responseMimeType: 'application/json',
          responseSchema: {
            type: 'OBJECT',
            properties: {
              abc: { type: 'STRING' },
            },
            required: ['abc'],
          },
        },
      }),
    }
  );

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Gemini API error (${response.status}): ${errText}`);
  }

  const data = await response.json();
  const text = data?.candidates?.[0]?.content?.parts?.map((p) => p.text || '').join('') || '';

  try {
    const parsed = JSON.parse(text);
    return parsed.abc || '';
  } catch (e) {
    // 万一JSONで返らなかった場合の保険として、従来通りのMarkdownコードブロック抽出も試す
    return text;
  }
}

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    res.status(405).json({ error: 'Method Not Allowed' });
    return;
  }

  const { bpm, level } = req.body || {};

  if (!bpm || !level) {
    res.status(400).json({ error: 'bpm/levelが指定されていません。' });
    return;
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    res.status(500).json({ error: 'サーバー側にGEMINI_API_KEYが設定されていません。' });
    return;
  }

  const model = 'gemini-3.5-flash-lite';

  try {
    const prompt = buildPrompt(bpm, level);
    const rhythmData = await callGemini({ apiKey, model, prompt });

    // クライアント側の既存ロジックがそのまま使える形(旧Dify版と同じネスト構造)で返す
    res.status(200).json({ data: { outputs: { rhythm_data: rhythmData } } });
  } catch (err) {
    console.error('rhythmmaster gemini handler error:', err);
    res.status(500).json({
      error: 'リズムの生成中にエラーが発生しました。',
      debugDetail: String(err && err.message ? err.message : err),
    });
  }
}
